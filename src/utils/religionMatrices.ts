// ============================================================================
// Helper: Retrieve the Authentic Religion Matrix based on Subject & Fase
// ============================================================================
export function getReligionMatrix(subjectName: string, fase: string): ReligionMatrix | null {
  const s = (subjectName || '').toLowerCase();
  const isIslam = s.includes('pai') || s.includes('islam') || s.includes('paibp');
  const isKristen = s.includes('kristen') || s.includes('protestan') || s.includes('pakbp') || s.includes('pak');
  const isKatolik = s.includes('katolik') || s.includes('paktbp');

  if (isIslam) {
    if (fase === 'Fase A') return PAIBP_SD_FASE_A_MATRIX;
    if (fase === 'Fase B') return PAIBP_SD_FASE_B_MATRIX;
    if (fase === 'Fase C') return PAIBP_SD_FASE_C_MATRIX;
    if (fase === 'Fase D') return PAIBP_SMP_FASE_D_MATRIX;
    if (fase === 'Fase E') return PAIBP_SMA_FASE_E_MATRIX;
    if (fase === 'Fase F') return PAIBP_SMA_FASE_F_MATRIX;
  }

  if (isKristen) {
    if (fase === 'Fase D') return PAK_SMP_FASE_D_MATRIX;
    if (fase === 'Fase E' || fase === 'Fase F') return PAK_SMP_FASE_D_MATRIX;
  }

  if (isKatolik) {
    if (fase === 'Fase D') return KATOLIK_SMP_FASE_D_MATRIX;
    if (fase === 'Fase E' || fase === 'Fase F') return KATOLIK_SMP_FASE_D_MATRIX;
  }

  return null;
}
